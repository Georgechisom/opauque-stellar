#[allow(clippy::too_many_arguments)]
fn run_pairing_check(
    env: &Env,
    proof_a: [u8; 64],
    proof_b: [u8; 128],
    proof_c: [u8; 64],
    vk_x: [u8; 64],
    vk_alpha: &[u8; 64],
    vk_beta: &[u8; 128],
    vk_gamma: &[u8; 128],
    vk_delta: &[u8; 128],
) -> Result<bool, VerifierError> {
    let mut neg_a = proof_a;
    let a_y = &proof_a[32..64];
    let neg_a_y = field_negate(a_y);
    neg_a[32..64].copy_from_slice(&neg_a_y);

    let mut pairing_input = [0u8; 768];
    let mut offset = 0usize;
    for chunk in [
        neg_a.as_slice(),
        proof_b.as_slice(),
        vk_alpha.as_slice(),
        vk_beta.as_slice(),
        vk_x.as_slice(),
        vk_gamma.as_slice(),
        proof_c.as_slice(),
        vk_delta.as_slice(),
    ] {
        pairing_input[offset..offset + chunk.len()].copy_from_slice(chunk);
        offset += chunk.len();
    }
    alt_bn128_pairing(env, &pairing_input)
}

