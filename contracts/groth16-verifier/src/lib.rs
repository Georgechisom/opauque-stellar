#![no_std]
use soroban_sdk::crypto::bn254::{Bn254G1Affine, Bn254G2Affine, Fr};
use soroban_sdk::{contract, contracterror, contractimpl, contracttype, BytesN, Env, Vec};

/// On-chain Groth16 verifier using Stellar's supported BN254 host functions.
#[contract]
pub struct Groth16Verifier;

#[contracttype]
#[derive(Clone)]
pub struct VerifyPublicInputsV2 {
    pub merkle_root: BytesN<32>,
    pub attestation_id: BytesN<32>,
    pub external_nullifier: BytesN<32>,
    pub nullifier_hash: BytesN<32>,
}

/// Public inputs for the V3 privacy-pool withdraw circuit (6 signals). Order is
/// load-bearing and must match circuits/v3/privacy_pool_withdraw.circom and the
/// frontend pool prover: withdrawn_value, state_root, asp_root, nullifier_hash,
/// new_commitment, context.
#[contracttype]
#[derive(Clone)]
pub struct VerifyPublicInputsV3 {
    pub withdrawn_value: BytesN<32>,
    pub state_root: BytesN<32>,
    pub asp_root: BytesN<32>,
    pub nullifier_hash: BytesN<32>,
    pub new_commitment: BytesN<32>,
    pub context: BytesN<32>,
}

#[contracterror]
#[derive(Copy, Clone, Debug, Eq, PartialEq, PartialOrd, Ord)]
#[repr(u32)]
pub enum VerifierError {
    InvalidPublicSignal = 1,
    Bn128AdditionFailed = 2,
    Bn128MultiplicationFailed = 3,
    Bn128PairingFailed = 4,
}

#[contractimpl]
impl Groth16Verifier {
    pub fn verify_proof(
        env: Env,
        proof_a: BytesN<64>,
        proof_b: BytesN<128>,
        proof_c: BytesN<64>,
        pub_signals: soroban_sdk::Vec<BytesN<32>>,
    ) -> Result<bool, VerifierError> {
        if pub_signals.len() != 5 {
            return Err(VerifierError::InvalidPublicSignal);
        }
        for i in 0..5u32 {
            let signal = pub_signals.get(i).unwrap();
            if !is_valid_scalar(&signal.to_array()) {
                return Err(VerifierError::InvalidPublicSignal);
            }
        }
        let mut vk_x = VK_IC[0];
        for i in 0..5 {
            let signal = pub_signals.get(i as u32).unwrap().to_array();
            let mul_result = alt_bn128_g1_mul(&env, &VK_IC[i + 1], &signal)?;
            vk_x = alt_bn128_g1_add(&env, &vk_x, &mul_result)?;
        }
        run_pairing_check(
            &env,
            proof_a.to_array(),
            proof_b.to_array(),
            proof_c.to_array(),
            vk_x,
            &VK_ALPHA,
            &VK_BETA,
            &VK_GAMMA,
            &VK_DELTA,
        )
    }

    pub fn verify_proof_v2(
        env: Env,
        proof_a: BytesN<64>,
        proof_b: BytesN<128>,
        proof_c: BytesN<64>,
        public_inputs: VerifyPublicInputsV2,
    ) -> Result<bool, VerifierError> {
        let pub_signals = [
            public_inputs.merkle_root.to_array(),
            public_inputs.attestation_id.to_array(),
            public_inputs.external_nullifier.to_array(),
            public_inputs.nullifier_hash.to_array(),
        ];
        for signal in &pub_signals {
            if !is_valid_scalar(signal) {
                return Err(VerifierError::InvalidPublicSignal);
            }
        }
        let mut vk_x = VK_IC_V2[0];
        for i in 0..4 {
            let mul_result = alt_bn128_g1_mul(&env, &VK_IC_V2[i + 1], &pub_signals[i])?;
            vk_x = alt_bn128_g1_add(&env, &vk_x, &mul_result)?;
        }
        run_pairing_check(
            &env,
            proof_a.to_array(),
            proof_b.to_array(),
            proof_c.to_array(),
            vk_x,
            &VK_ALPHA_V2,
            &VK_BETA_V2,
            &VK_GAMMA_V2,
            &VK_DELTA_V2,
        )
    }

    /// Verify a V3 privacy-pool withdraw proof (6 public signals / 7 IC points).
    pub fn verify_proof_v3(
        env: Env,
        proof_a: BytesN<64>,
        proof_b: BytesN<128>,
        proof_c: BytesN<64>,
        public_inputs: VerifyPublicInputsV3,
    ) -> Result<bool, VerifierError> {
        let pub_signals = [
            public_inputs.withdrawn_value.to_array(),
            public_inputs.state_root.to_array(),
            public_inputs.asp_root.to_array(),
            public_inputs.nullifier_hash.to_array(),
            public_inputs.new_commitment.to_array(),
            public_inputs.context.to_array(),
        ];
        for signal in &pub_signals {
            if !is_valid_scalar(signal) {
                return Err(VerifierError::InvalidPublicSignal);
            }
        }
        let mut vk_x = VK_IC_V3[0];
        for i in 0..6 {
            let mul_result = alt_bn128_g1_mul(&env, &VK_IC_V3[i + 1], &pub_signals[i])?;
            vk_x = alt_bn128_g1_add(&env, &vk_x, &mul_result)?;
        }
        run_pairing_check(
            &env,
            proof_a.to_array(),
            proof_b.to_array(),
            proof_c.to_array(),
            vk_x,
            &VK_ALPHA_V3,
            &VK_BETA_V3,
            &VK_GAMMA_V3,
            &VK_DELTA_V3,
        )
    }
}

